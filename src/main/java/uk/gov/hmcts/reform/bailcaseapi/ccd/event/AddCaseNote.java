package uk.gov.hmcts.reform.bailcaseapi.ccd.event;

import org.springframework.beans.factory.ObjectProvider;
import org.springframework.stereotype.Component;
import uk.gov.hmcts.ccd.sdk.api.CCDConfig;
import uk.gov.hmcts.ccd.sdk.api.ConfigBuilder;
import uk.gov.hmcts.ccd.sdk.api.Permission;
import uk.gov.hmcts.reform.bailcaseapi.ccd.callback.AddCaseNoteCallbacks;
import uk.gov.hmcts.reform.bailcaseapi.ccd.model.CaseData;
import uk.gov.hmcts.reform.bailcaseapi.ccd.model.State;
import uk.gov.hmcts.reform.bailcaseapi.ccd.model.UserRole;

/**
 * Event {@code addCaseNote} for case type {@code Bail}.
 *
 * <p>Originally generated by ccd-definition-converter and since adopted: its callbacks are the
 * SDK's own rather than URLs pointing back at {@code /bail/ccdAboutToSubmit}, so regenerating the
 * tree would overwrite this file. Everything below the callbacks is still as generated.
 */
@Component
public class AddCaseNote implements CCDConfig<CaseData, State, UserRole> {
    /**
     * The CCD event ID.
     */
    public static final String ADD_CASE_NOTE = "addCaseNote";

    private final ObjectProvider<AddCaseNoteCallbacks> callbacks;

    public AddCaseNote(ObjectProvider<AddCaseNoteCallbacks> callbacks) {
        this.callbacks = callbacks;
    }

    /**
     * Registers event {@code addCaseNote}.
     *
     * @param builder the config builder
     */
    @Override
    public void configure(ConfigBuilder<CaseData, State, UserRole> builder) {
        var fields = builder.event(ADD_CASE_NOTE)
            .forStates(State.applicationSubmitted, State.bailSummaryUploaded, State.unsignedDecision, State.decisionConditionalBail, State.decisionDecided, State.applicationEnded)
            .name("Add case note")
            .displayOrder(7)
            .showSummary()
            .endButtonLabel("Add case note")
            .aboutToSubmitCallback(
                (details, detailsBefore) -> callbacks.getObject().aboutToSubmit(details, detailsBefore),
                5, 5, 5, 5)
            .submittedCallback(
                (details, detailsBefore) -> callbacks.getObject().submitted(details, detailsBefore),
                5, 5, 5, 5)
            .explicitGrants()
            .grant(Permission.CRUD, UserRole.CASEWORKER_IA_ADMOFFICER, UserRole.CASEWORKER_IA_IACJUDGE, UserRole.CASEWORKER_IA_RPAROBOT)
            .fields();
        fields.page("addCaseNote");
        fields.pageLabel("Case note details");
        fields.readonly(CaseData::getAddCaseNoteLabel);
        fields.mandatory(CaseData::getAddCaseNoteSubject);
        fields.mandatory(CaseData::getAddCaseNoteDescription);
        fields.optional(CaseData::getAddCaseNoteDocument);
    }
}
